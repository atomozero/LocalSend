static Language sCurrentLang = kLangItalian;

inline const char*
Tr(StringId id)
{
	return sStrings[id][sCurrentLang];
}

inline void
SetLanguage(Language lang)
{
	sCurrentLang = lang;
}

inline void
SetLanguageFromName(const char* name)
{
	if (!name || !*name)
		return;
	// Confronta i primi 2 caratteri (codice lingua ISO 639-1).
	if (strncmp(name, "en", 2) == 0) sCurrentLang = kLangEnglish;
	else if (strncmp(name, "it", 2) == 0) sCurrentLang = kLangItalian;
	else if (strncmp(name, "ja", 2) == 0) sCurrentLang = kLangJapanese;
	else if (strncmp(name, "zh", 2) == 0) sCurrentLang = kLangChinese;
	else if (strncmp(name, "es", 2) == 0) sCurrentLang = kLangSpanish;
}

inline const char*
LanguageName(Language lang)
{
	switch (lang) {
		case kLangItalian:  return "Italiano";
		case kLangEnglish:  return "English";
		case kLangJapanese: return "\xe6\x97\xa5\xe6\x9c\xac\xe8\xaa\x9e"; // 日本語
		case kLangChinese:  return "\xe4\xb8\xad\xe6\x96\x87"; // 中文
		case kLangSpanish:  return "Espa\xc3\xb1ol";
		default: return "?";
	}
}

inline const char*
LanguageCode(Language lang)
{
	switch (lang) {
		case kLangItalian:  return "it";
		case kLangEnglish:  return "en";
		case kLangJapanese: return "ja";
		case kLangChinese:  return "zh";
		case kLangSpanish:  return "es";
		default: return "it";
	}
}

